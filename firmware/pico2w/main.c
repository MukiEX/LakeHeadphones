/* ------------------------------------------------------------------ USB service (timer IRQ) */
/* Everything that touches TinyUSB lives here, so it all runs in one context. */
static bool usb_service_cb(repeating_timer_t *t)
{
    (void)t;
    tud_task();
    usb_pump();
    usb_audio51_service();                    /* media keys from the headset */
#if LHP_WEBCFG
    if (usb_audio51_has_network()) webcfg_usb_service();
#endif
#if LHP_DEBUG_CDC
    dbg_cdc_task();
#endif
    return true;
}

/* Runs right after TinyUSB's own USB interrupt handler (same IRQ, lowest
 * order), so a finished isochronous packet is re-armed within microseconds.
 * Waiting for the 250 us timer was usually fine, but when the host happened to
 * send two packets close together (end of one frame, start of the next) the
 * second one found the endpoint unarmed and was lost: a click. The timer and
 * this handler share one priority, so tud_task() never runs nested. */
static void usb_irq_task(void) { tud_task(); }

