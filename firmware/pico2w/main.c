static void usb_pump(void)
{
    static int16_t tmp[64 * USB_AUDIO51_MAX_CHANNELS];
    for (;;) {
        const uint32_t cap = usb_audio51_fifo_frames();
        uint32_t want = dhp_usb_frames_wanted_guarded(&g_pipe, usb_audio51_frames_available(),
                                                      cap * 3 / 4, cap / 2);
        if (!want) break;
        if (want > 64) want = 64;
        uint32_t got = usb_audio51_read(tmp, want);
        if (!got) break;
        dhp_usb_write(&g_pipe, tmp, got);
        g_usb_frames += got;
    }
}

/* ------------------------------------------------------------------ core 1 */
static volatile bool g_bt_ready;          /* set by core 1 once CYW43 + BTstack are up */
/* timing stats (debug status line) */
static volatile uint32_t g_dsp_us_sum, g_dsp_n, g_dsp_us_max, g_enc_us_sum, g_enc_n, g_enc_us_max;
static volatile uint32_t g_dsp_us_total, g_enc_us_total;   /* never reset: for the settings page */
static void led_apply_core1(void);

static void core1_main(void)
{
    multicore_lockout_victim_init();       /* lets core 0 pause us for flash/BOOTSEL */
    if (cyw43_arch_init()) { printf("cyw43 init failed\n"); for (;;) tight_loop_contents(); }
    bt_a2dp_init();
    g_bt_ready = true;
    for (;;) {
        uint32_t t0 = time_us_32();
        bool did = dhp_dsp_poll(&g_pipe);
        if (did) {
            uint32_t dt = time_us_32() - t0;
            g_dsp_us_sum += dt; g_dsp_n++; g_dsp_us_total += dt;
            if (dt > g_dsp_us_max) g_dsp_us_max = dt;
        }
        led_apply_core1();
        if (!did) busy_wait_us_32(50);
    }
}

/* ------------------------------------------------------------------ sink (core 0) */
static void sink_task(void)
{
    static uint64_t vs_t0, vs_done;
    if (!g_bt_ready) return;
    if (bt_a2dp_streaming()) {
        uint32_t t0 = time_us_32();
        if (bt_a2dp_encoder_service(&g_pipe)) {
            uint32_t dt = time_us_32() - t0;
            g_enc_us_sum += dt; g_enc_n++; g_enc_us_total += dt;
            if (dt > g_enc_us_max) g_enc_us_max = dt;
        }
        vs_t0 = time_us_64(); vs_done = 0;
    } else {
        bt_a2dp_encoder_service(&g_pipe);   /* applies codec config changes */
        /* No headset streaming: drain at 48 kHz so USB timing stays sane. */
        if (!vs_t0) vs_t0 = time_us_64();
        uint64_t due = (time_us_64() - vs_t0) * 48 / 1000;
        while (due - vs_done >= 64) {
            int16_t junk[64 * 2];
            dhp_read_stereo(&g_pipe, junk, 64);
            vs_done += 64;
        }
    }
}

/* ------------------------------------------------------------------ button */
static bool __no_inline_not_in_flash_func(bootsel_raw)(void)
{
    const uint CS_PIN_INDEX = 1;
    uint32_t flags = save_and_disable_interrupts();
    hw_write_masked(&ioqspi_hw->io[CS_PIN_INDEX].ctrl,
                    GPIO_OVERRIDE_LOW << IO_QSPI_GPIO_QSPI_SS_CTRL_OEOVER_LSB,
                    IO_QSPI_GPIO_QSPI_SS_CTRL_OEOVER_BITS);
    for (volatile int i = 0; i < 1000; ++i);
#if PICO_RP2040
    const uint32_t CS_BIT = 1u << 1;
#else
    const uint32_t CS_BIT = SIO_GPIO_HI_IN_QSPI_CSN_BITS;
#endif
    bool pressed = !(sio_hw->gpio_hi_in & CS_BIT);
    hw_write_masked(&ioqspi_hw->io[CS_PIN_INDEX].ctrl,
                    GPIO_OVERRIDE_NORMAL << IO_QSPI_GPIO_QSPI_SS_CTRL_OEOVER_LSB,
                    IO_QSPI_GPIO_QSPI_SS_CTRL_OEOVER_BITS);
    restore_interrupts(flags);
    return pressed;
}

static bool button_pressed(void)
{
#if LHP_BUTTON_GPIO >= 0
    return !gpio_get(LHP_BUTTON_GPIO);
#else
    /* Flash is unusable while we sample BOOTSEL, so park core 1 first. */
    /* Lock out first, with interrupts still on: if core 1 is mid flash write
     * (BTstack storing the headset) it is locking *us* out and needs our IRQ. */
    multicore_lockout_start_blocking();
    uint32_t irq = save_and_disable_interrupts();
    bool b = bootsel_raw();
    restore_interrupts(irq);
    multicore_lockout_end_blocking();
    return b;
#endif
}

/* ------------------------------------------------------------------ LED */
static int  led_blinks;          /* pending room-change blinks */
/* The LED hangs off the CYW43, so every change is an SPI transaction that can
 * wait on the BT IRQ. Core 0 only records the wanted state; core 1 applies it. */
static volatile bool g_led_want;
static void led_set(bool on) { g_led_want = on; }
static void led_apply_core1(void)
{
    static int last = -1;
    const bool on = g_led_want;
    if (last == (int)on) return;
    last = on;
    cyw43_arch_gpio_put(CYW43_WL_GPIO_LED_PIN, on);
}

static void led_task(uint32_t now)
{
    static uint32_t t0;
    if (led_blinks) {                         /* N x (150 ms on, 150 ms off) */
        if (!t0) t0 = now;
        uint32_t ph = (now - t0) / 150;
        if (ph >= (uint32_t)led_blinks * 2 + 2) { led_blinks = 0; t0 = 0; }
        else { led_set(ph < (uint32_t)led_blinks * 2 && !(ph & 1)); return; }
    }
    switch (bt_a2dp_state()) {
    case BT_STREAMING:  led_set(true); break;                      /* solid: playing to the headset */
    case BT_CONNECTED:  led_set((now / 500) & 1); break;           /* slow blink: connected, idle   */
    case BT_SCANNING:   led_set((now / 100) & 1); break;           /* fast blink: pairing mode      */
    default:            led_set(now % 1000 < 80); break;           /* short blip each second:
                                                                      reconnecting to the remembered headset */
    }
}

static void button_task(uint32_t now)
{
    static uint32_t last_poll, down_at, released_at;
    static bool down, long_fired;
    static int clicks;
    if (g_reboot_at) return;
    if (now - last_poll < 20) return;
    last_poll = now;
    bool p = button_pressed();
    if (p && !down) { down = true; down_at = now; long_fired = false; }
    else if (p && down && !long_fired && now - down_at >= LONG_PRESS_MS) {
        long_fired = true;
        clicks = 0;
        bt_a2dp_forget_and_scan();
    } else if (!p && down) {
        down = false;
        if (!long_fired && now - down_at >= 30) { clicks++; released_at = now; }
    }
    if (!clicks || down || now - released_at <= MULTI_GAP_MS) return;
    if ((clicks < 3 || clicks == 4) && !g_have_filters) {
        led_blinks = 8;                         /* no filters: rooms unavailable */
        LOG0("No room filters loaded: add them with lakehp_flasher.html\n");
    } else if (clicks == 1) {
        int next = dhp_cycle_room(&g_pipe);
        led_blinks = next;
        LOG0("Room -> %s%s\n", dhp_room_name(next), dhp_low_latency(&g_pipe) ? " (applies when low-latency is off)" : "");
    } else if (clicks == 2) {
        bool on = dhp_toggle_low_latency(&g_pipe);
        led_blinks = on ? 4 : g_pipe.room;
        LOG0("Low-latency stereo %s\n", on ? "ON" : "OFF (rooms)");
    } else if (clicks == 3) {
        g_set.stereo = usb_audio51_is_stereo() ? 0 : 1;
        LOG0("USB mode -> %s, restarting\n", g_set.stereo ? "stereo (UAC1)" : g_set.ch8 ? "7.1 (UAC2)" : "5.1 (UAC2)");
        led_blinks = 6;
        g_reboot_at = now + 6 * 300 + 200;      /* after the blinks */
    } else if (clicks == 4) {
        lhp_surround_t sur, back;               /* 4 presses: Factory <-> Theater */
        dhp_get_placement(&g_pipe, &sur, &back);
        const int to = dhp_preset_of(&sur, &back) == DHP_PRESET_FACTORY ? DHP_PRESET_THEATER : DHP_PRESET_FACTORY;
        dhp_preset(to, &g_set.sur, &g_set.back);
        dhp_set_placement(&g_pipe, &g_set.sur, &g_set.back, true);
        settings_save();
        led_blinks = to == DHP_PRESET_THEATER ? 2 : 1;
        LOG0("Speaker placement -> %s\n", to == DHP_PRESET_THEATER ? "Theater (surrounds 136, backs 150 deg)" : "Factory");
    } else {
        g_set.web_off = !g_set.web_off;                /* 5 presses: settings adapter on/off */
        LOG0("Settings adapter -> %s, restarting\n", g_set.web_off ? "off" : "on");
        led_blinks = 5;
        g_reboot_at = now + 5 * 300 + 200;
    }
    clicks = 0;
}

static void reboot_task(uint32_t now)
{
    if (!g_reboot_at || (int32_t)(now - g_reboot_at) < 0) return;
    settings_save();
    watchdog_reboot(0, 0, 10);
    for (;;) tight_loop_contents();
}

