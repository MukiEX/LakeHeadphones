/*
 * LakeHP 5.1/7.1 -> Bluetooth headphone virtualizer, Raspberry Pi Pico 2 W.
 *
 *   core 0: TinyUSB (UAC2 5.1/7.1 speaker) runs from a 250 us timer interrupt.
 *           The RP2 USB driver re-arms the isochronous OUT endpoint only from
 *           tud_task(), so any gap over ~1 ms drops a USB packet (audible as
 *           fuzz); in an interrupt nothing on this core can delay it.
 *           The main loop does the sink side: SBC-encodes the Bluetooth audio
 *           (~0.45 ms per frame at 200 MHz), plus the button and LED.
 *   core 1: headphone virtualizer DSP (lakehp engine) and BTstack + CYW43 (their
 *           background IRQ is bound to the core that inits them).
 * The system clock runs at 200 MHz (RP2350 is fine there at 1.15 V); the
 * CYW43 SPI divider is scaled to keep its bus at the stock speed.
 *
 * Logging from core 0 must never block or take stdio's mutex (the main loop
 * could hold it when the USB interrupt wants it): it goes only to the
 * debug-build USB serial ring via LOG0 = dbg_logf().
 *
 * Button (BOOTSEL, or an optional GPIO button to GND):
 *   single press -> cycle Small / Medium / Large room (1/2/3 beeps + LED blinks)
 *   double press -> low-latency stereo on/off (2 high beeps = on)
 *   triple press -> USB mode: 5.1/7.1 (UAC2) <-> stereo (UAC1, for consoles such
 *                   as the Switch). Saved in flash; the Pico restarts (LED blinks 6x).
 *                   5.1 vs 7.1 is chosen on the settings page.
 *   4 presses    -> speaker placement preset: Factory <-> Theater (surrounds 136,
 *                   7.1 backs 150 deg) (1 low beep = Factory, 2 = Theater). Saved.
 *   5 presses    -> settings page network adapter on/off (restarts).
 *   hold 2 s     -> forget the paired headset and scan for a new one
 */
